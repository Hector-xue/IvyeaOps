/**
 * 「后一段把前一段整段重抄了一遍」的判据。
 *
 * ── 这是在修什么 ──────────────────────────────────────────────────────────
 * 一轮里 agent 的形状是「说一段 → 调几个工具 → 再说一段」，界面按这个形状把每一
 * 段话铺成一块（见 lib/turnStream 的 sealSegment 与 lib/sessionRestore）。这套东西
 * 的前提是：工具跑完之后模型**接着往下说**。
 *
 * 有些模型不是这样。实测 z-ai/glm-5.3-flash：每次工具调用之后，它会把已经说过的
 * 那张表从头到尾再抄一遍，只在末尾添一行新的。界面忠实地把每一稿都留着，于是同
 * 一张表连出三遍，越往后屏幕越被它占满 —— 用户原话："总不能增加一条新内容就把
 * 整个都输出一遍吧"。
 *
 * ── 为什么判据是"逐字前缀"而不是相似度 ───────────────────────────────────
 * 这里做的是**删掉用户已经看过的内容**，判错的代价是吞掉一段真话。所以只认最硬
 * 的那种证据：归一化空白之后，后一段以前一段**一字不差**地开头。改了一个字就不
 * 算重述，宁可漏掉一次合并，也不能吞掉两段真的不同的话。
 *
 * 长度下限是同一个道理：短句的前缀撞车太容易（"好的，我看一下"谁都可能再说一
 * 次），几十个字以上的逐字重合才不可能是巧合。
 */

/** 归一化后至少这么长才判重。短于此的前缀重合当巧合处理。 */
const RESTATE_MIN = 40;

/**
 * 归一化。
 *
 * 除了空白，还要把 **Markdown 表格分隔行里的短横**收成固定长度 —— 否则表格这一类
 * 内容会绕过整个判据：
 *
 *   第一稿  `| 商品 | 售价 |` / `| ---- | ---- |` / 两行数据
 *   第二稿  加了一行「超长商品名称」，于是**整张表的列宽重新对齐**，
 *           分隔行跟着变成 `| ------------ | ---- |`
 *
 * 空白被 `\s+` 收掉了，可短横不是空白 —— 逐字前缀在分隔行那里断掉，去重漏判，
 * 界面上两张表都留着。这正是用户报的「新增一行又会重头把这个输出一遍」。
 * （只加行、列宽不变时判据一直是对的，所以此前没暴露。）
 *
 * 只动分隔行：`|---|:--:|` 这种整行只由 `| - : 空格` 组成的行，它的短横数量不携带
 * 任何信息。正文里的 `---`（分割线）和 `--` 不受影响。
 */
const norm = (s: string) =>
  (s || "")
    .split("\n")
    .map((line) =>
      /^\s*\|[\s\-:|]+\|\s*$/.test(line) && line.includes("-")
        ? line.replace(/-{2,}/g, "-")
        : line,
    )
    .join("\n")
    .replace(/\s+/g, " ")
    .trim();

/**
 * `next` 里**原封不动地包含**着整个 `prev`（含一字不差的完全重复）。
 *
 * ── 为什么从"前缀"放宽到"包含" ───────────────────────────────────────────
 * 前缀判据只认"从头抄一遍"。实测 glm-5.3-flash 不是这么抄的：它重抄的是**手上
 * 正在写的那张表**，而不是整篇 ——
 *
 *   第一稿  `### 1. 大厂具名薪资` + 表头 + 1 行
 *   第二稿  表头 + 3 行          ← 没带上那个标题，于是"以第一稿开头"不成立
 *   第三稿  表头 + 4 行
 *
 * 三稿一稿不落全留在屏幕上，就是用户报的"还是一个劲的重复输出"。但它们有一条共同
 * 性质：**每一稿都一字不差地躺在后面某一稿（最终那一稿）里面**。改判"被后面某一
 * 稿完整包含"就同时收住这两种抄法。
 *
 * 判错的代价没有变大：被丢掉的那一段，它的**每一个字**都还在留下来的那一段里，
 * 用户一个字都不会少看 —— 少的只是同一段话的第二遍。这也是这里敢放宽、而不敢换成
 * 相似度的原因：相似度会把"改了一个数字的新版本"判成重复，那才是真的吞话。
 *
 * 注意方向：只有**后来的那一段**能作废先前的那一段。反过来（前一段更长）说明
 * 模型这次没抄完，那是两段不同的话，不合并。
 */
export function restates(prev: string, next: string): boolean {
  const a = norm(prev);
  const b = norm(next);
  return a.length >= RESTATE_MIN && b.length >= a.length && b.includes(a);
}

/**
 * 一串正文里，哪几段被后面的某一段整段重写了。返回它们的下标集合。
 *
 * 拿下标而不是直接过滤，是因为调用方各有各的要收拾的东西：铺块的那头要连着这段
 * 话下面挂的执行过程一起排，恢复存档的那头要把这一格留着（步骤还挂在上面）、只
 * 把正文清掉。
 */
export function restatedIndexes(texts: string[]): Set<number> {
  const drop = new Set<number>();
  // **从后往前**：判一段该不该丢，看的是它后面**还留着**的那些段。顺着来的话
  // 后面那些还没判过，会拿一段自己也要被丢掉的稿子去作废前一段。
  const drops = (i: number) => {
    for (let j = i + 1; j < texts.length; j++) {
      if (drop.has(j)) continue;
      if (restates(texts[i], texts[j])) return true;
    }
    return false;
  };
  for (let i = texts.length - 2; i >= 0; i--) if (drops(i)) drop.add(i);
  return drop;
}
