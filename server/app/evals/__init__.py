"""AI 输出质量评测。

**为什么它是"开放生态的前置条件"而不是锦上添花**：一旦门道的 Skill 市场开放、
社区开始提"我优化了广告诊断的提示词"这类 PR，**没有评测就没有任何办法判断这个
改动是变好还是变坏** —— 合并就是赌博。功能测试在这里帮不上忙：提示词改动不会让
任何断言变红，它只会让输出悄悄变差。

三层，各管各的事
----------------
1. **确定性回归**（``deterministic.py``）：规则引擎、费用计算、签名、报告解析这些
   **有唯一正确答案**的部分，固定输入断言精确输出。跑得快、零成本、每次 CI 都跑。
2. **Rubric 评分**（``rubric.py``）：LLM 产出没有唯一正确答案，但有**可判定的
   质量维度**。用另一个模型按固定评分标准打分，多次取中位数降抖动。
3. **影子回归**：新旧提示词同时跑同一批真实任务，只记录不生效，产出差异报告。
   （IvyeaAgent 侧已有 ``shadow.py``，这里不重复造。）

为什么判官必须换一个模型
------------------------
同一个模型给自己打分会系统性偏高 —— 它认可的正是它自己会产出的那种东西。
``rubric`` 因此强制要求判官与被测不同，配置不满足时**跳过并说明**，
而不是用"自己判自己"凑一个好看的分数。
"""
